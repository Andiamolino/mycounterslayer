import { expect, type Download, type Locator, type Page } from '@playwright/test';
import { readFile } from 'node:fs/promises';

// Shared locators and helpers for the F2 (project name) E2E tests.

export const DEFAULT_NAME = 'Untitled Project';
export const STORAGE_KEY = 'counter-tray-project';
export const TITLE_SUFFIX = ' – Counter Slayer';

// --- Locators -------------------------------------------------------------

export function headerButton(page: Page): Locator {
  return page.getByTitle('Rename project');
}

export function headerInput(page: Page): Locator {
  return page.getByRole('textbox', { name: 'Project name' });
}

export function panelNameField(page: Page): Locator {
  return page.locator('.globalsPanel').getByLabel('Name', { exact: true }).first();
}

export function exportDialog(page: Page): Locator {
  return page.getByRole('dialog', { name: 'Export project JSON' });
}

// --- Helpers --------------------------------------------------------------

export async function openApp(page: Page): Promise<void> {
  await page.goto('/');
  await expect(headerButton(page)).toBeVisible();
  await expect(panelNameField(page)).toBeVisible();
}

export async function expectProjectName(page: Page, name: string): Promise<void> {
  await expect(headerButton(page)).toContainText(name);
  await expect(panelNameField(page)).toHaveValue(name);
  await expect(page).toHaveTitle(name + TITLE_SUFFIX);
}

export async function renameInHeader(page: Page, typed: string): Promise<void> {
  await headerButton(page).click();
  await expect(headerInput(page)).toBeFocused();
  await headerInput(page).fill(typed);
  await headerInput(page).press('Enter');
}

export async function openExportDialog(page: Page): Promise<Locator> {
  await page.getByRole('button', { name: 'Import / Export' }).first().click();
  await page.getByRole('button', { name: 'Export project JSON' }).click();
  const dialog = exportDialog(page);
  await expect(dialog).toBeVisible();
  return dialog;
}

export async function readDownloadJson(download: Download): Promise<Record<string, unknown>> {
  const filePath = await download.path();
  return JSON.parse(await readFile(filePath, 'utf8'));
}

// Export the current project through the dialog with the proposed name
export async function exportCurrentProject(page: Page): Promise<{ download: Download; json: Record<string, unknown> }> {
  const dialog = await openExportDialog(page);
  const downloadPromise = page.waitForEvent('download');
  await dialog.getByRole('button', { name: 'Save' }).click();
  const download = await downloadPromise;
  return { download, json: await readDownloadJson(download) };
}

export async function importJson(page: Page, fileName: string, data: unknown): Promise<void> {
  await page
    .locator('input[type="file"][accept=".json"]')
    .first()
    .setInputFiles({
      name: fileName,
      mimeType: 'application/json',
      buffer: Buffer.from(JSON.stringify(data))
    });
}

// Fail the test if a download starts within the given time window
export async function expectNoDownload(page: Page, action: () => Promise<void>, waitMs = 1000): Promise<void> {
  let downloadCount = 0;
  const onDownload = () => downloadCount++;
  page.on('download', onDownload);
  await action();
  await page.waitForTimeout(waitMs);
  page.off('download', onDownload);
  expect(downloadCount).toBe(0);
}

// --- Import / Export menu -------------------------------------------------

export function importExportButton(page: Page): Locator {
  return page.getByRole('button', { name: 'Import / Export' }).first();
}

export function anyDialog(page: Page): Locator {
  return page.getByRole('dialog');
}

// Open the Import / Export popover unless the requested item is already visible
export async function openMenuItem(page: Page, itemName: string): Promise<Locator> {
  const item = page.getByRole('button', { name: itemName, exact: true });
  if (!(await item.isVisible())) {
    await importExportButton(page).click();
  }
  await expect(item).toBeVisible();
  return item;
}

// Geometry is generated by a web worker; wait until the generating overlay is gone.
// The initial generation starts right after load, so first give it a moment to appear.
export async function waitForGeometry(page: Page, timeout = 120_000): Promise<void> {
  const overlay = page.locator('.generatingOverlay');
  try {
    await overlay.first().waitFor({ state: 'visible', timeout: 3_000 });
  } catch {
    // Generation may already be finished (or not started for an empty project)
  }
  await expect(overlay).toHaveCount(0, { timeout });
}
